-- 01_setup.sql
-- Run this first, as a user with ACCOUNTADMIN or SYSADMIN privileges.

CREATE WAREHOUSE IF NOT EXISTS RETAILPULSE_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'RetailPulse project warehouse';

CREATE DATABASE IF NOT EXISTS RETAILPULSE
    COMMENT = 'RetailPulse data platform';

CREATE SCHEMA IF NOT EXISTS RETAILPULSE.RAW;
CREATE SCHEMA IF NOT EXISTS RETAILPULSE.BRONZE;
CREATE SCHEMA IF NOT EXISTS RETAILPULSE.SILVER;
CREATE SCHEMA IF NOT EXISTS RETAILPULSE.GOLD;

USE WAREHOUSE RETAILPULSE_WH;
USE DATABASE RETAILPULSE;